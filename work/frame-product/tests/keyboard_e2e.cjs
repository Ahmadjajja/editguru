// Run from the repository root. Uses only the current Codex chat's owned browser.
const {execFileSync}=require('node:child_process');
const fs=require('node:fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const thread=process.env.CODEX_THREAD_ID,footage=process.env.FRAME_FOOTAGE;
if(!thread||!footage)throw Error('CODEX_THREAD_ID and FRAME_FOOTAGE (video at least 8 seconds) are required');
const manager='/Users/dantegarcia/Desktop/tools/agent-pov-monitor/agent-session';
const owned=JSON.parse(execFileSync(manager,['allocate',thread],{encoding:'utf8'}));
fs.mkdirSync('output/playwright',{recursive:true});
(async()=>{
 const browser=await chromium.connectOverCDP('http://127.0.0.1:'+owned.debug_port);
 const page=browser.contexts()[0].pages()[0];
 const checks=[];
 const assert=(value,name)=>{if(!value)throw Error(name);checks.push(name)};
 const guard=async()=>{execFileSync(manager,['guard',thread])};
 const press=async key=>{await guard();await page.keyboard.press(key)};
 await guard();await page.goto('http://127.0.0.1:8876/quick');
 await page.waitForSelector('#file');await page.waitForFunction(()=>document.activeElement.tagName==='ASIDE');
 const picker=page.waitForEvent('filechooser',{timeout:15000});await press('Meta+o');
 const chooser=await picker;await guard();await chooser.setFiles(footage);
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Imported.'));
 await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
 assert(await page.locator('aside').evaluate(e=>e===document.activeElement),'Import returns keyboard focus');
 const state=async()=>page.evaluate(async()=>{const id=localStorage.getItem('frame-quick-project');return await(await fetch('/api/quick/projects/'+id)).json()});
 const wait=async version=>page.waitForFunction(v=>parseInt(document.querySelector('#saved').textContent.slice(1))>v,version);
 const change=async key=>{let before=await state();await press(key);await wait(before.version);return state()};
 let original=await state();assert(original.clips.length===1&&original.source_duration>=8,'Recorded footage imported');
 await press('Home');await press('ArrowRight');
 assert(Math.abs(Number(await page.locator('#seek').inputValue())-1/30)<1e-6,'Single-frame step');
 await press('Shift+ArrowRight');assert(Math.abs(Number(await page.locator('#seek').inputValue())-11/30)<1e-6,'Ten-frame step');
 await press('Home');for(let i=0;i<6;i++)await press('Shift+ArrowRight');
 let split=await change('s');assert(split.clips.length===2&&Math.abs(split.clips[0].end-2)<1e-6,'Keyboard split at 2 seconds');
 await press(']');for(let i=0;i<3;i++)await press('Shift+ArrowRight');
 let trimmed=await change('i');assert(Math.abs(trimmed.clips[1].start-3)<1e-6,'Keyboard trim in to source 3 seconds');
 assert(Math.abs(Number(await page.locator('#seek').inputValue())-2)<1e-6,'Trim in preserves source frame at playhead');
 let undo=await change('Meta+z');assert(undo.clips[1].start===2,'Keyboard undo');
 let redo=await change('Meta+Shift+z');assert(redo.clips[1].start===3,'Keyboard redo');
 await press('[');let deleted=await change('Backspace');assert(deleted.clips.length===1&&deleted.clips[0].start===3,'Keyboard delete selected first clip');
 await press('Home');for(let i=0;i<15;i++)await press('Shift+ArrowRight');
 let out=await change('o');assert(Math.abs(out.duration-5)<1e-6&&out.clips[0].end===8,'Keyboard trim out yields 5 seconds');
 await press('Home');await press('l');await page.waitForFunction(()=>document.querySelector('video').currentTime>3.3);await press('k');
 assert(await page.locator('video').evaluate(v=>v.paused&&v.currentTime>=3.3&&!v.error),'Edited source preview advances and pauses');
 await press('Meta+e');await page.waitForFunction(()=>!!document.querySelector('#exports a.download'),null,{timeout:120000});
 const done=await state();const exp=done.exports.at(-1);assert(exp.status==='done'&&Math.abs(exp.measured_duration-5)<.04,'Keyboard MP4 export completes');
 await page.screenshot({path:'output/playwright/keyboard-editor.png'});
 const url=exp.url;
 await guard();await page.goto(new URL(url,'http://127.0.0.1:8876').href);
 await page.waitForSelector('video');await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
 await page.locator('video').evaluate(v=>{v.muted=true;return v.play()});
 await page.waitForFunction(()=>document.querySelector('video').ended,null,{timeout:20000});
 assert(await page.locator('video').evaluate(v=>!v.error&&v.duration>=4.99&&v.duration<5.04),'Export plays to completion in Chrome');
 console.log(JSON.stringify({checks,project:done,source:footage},null,2));
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
